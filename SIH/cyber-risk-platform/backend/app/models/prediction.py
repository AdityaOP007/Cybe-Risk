import uuid
from datetime import datetime
from typing import TYPE_CHECKING, Any
from sqlalchemy import String, ForeignKey, Float, DateTime, CheckConstraint, Integer, Numeric
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base
from app.models.mixins import UUIDMixin, get_utc_now

if TYPE_CHECKING:
    from app.models.organization import Organization
    from app.models.asset import Asset
    from app.models.risk import RiskScore

class RiskPredictionModel(Base, UUIDMixin):
    """
    Registry for Machine Learning Models.
    """
    __tablename__ = "risk_prediction_models"

    name: Mapped[str] = mapped_column(String(100), index=True, nullable=False)
    version: Mapped[str] = mapped_column(String(50), nullable=False)
    model_type: Mapped[str] = mapped_column(String(100), nullable=False) # e.g. "RandomForestRegressor"
    dataset_version: Mapped[str] = mapped_column(String(100), nullable=False)
    feature_version: Mapped[str] = mapped_column(String(100), nullable=False)
    
    metrics: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True) # MAE, RMSE, R2
    hyperparameters: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)
    
    training_started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    training_completed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    
    training_data_start: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    training_data_end: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    
    status: Mapped[str] = mapped_column(String(50), default="active", nullable=False)
    artifact_path: Mapped[str] = mapped_column(String(500), nullable=False) # e.g. "models/rf_v1.0.joblib"
    
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=get_utc_now, nullable=False)

class RiskPrediction(Base, UUIDMixin):
    """
    Stores an individual risk prediction generated by a model.
    """
    __tablename__ = "risk_predictions"
    __table_args__ = (
        CheckConstraint("forecast_horizon_days > 0", name="chk_prediction_horizon"),
        CheckConstraint("confidence >= 0 AND confidence <= 100", name="chk_prediction_confidence"),
    )

    organization_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE"), index=True, nullable=False
    )
    asset_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("assets.id", ondelete="CASCADE"), index=True, nullable=False
    )
    risk_score_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("risk_scores.id", ondelete="CASCADE"), index=True, nullable=False
    )

    forecast_horizon_days: Mapped[int] = mapped_column(Integer, index=True, nullable=False)
    
    predicted_risk: Mapped[float] = mapped_column(Float, nullable=False)
    lower_bound: Mapped[float] = mapped_column(Float, nullable=False)
    upper_bound: Mapped[float] = mapped_column(Float, nullable=False)
    
    trend: Mapped[str] = mapped_column(String(50), nullable=False) # increasing, decreasing, stable
    confidence: Mapped[float] = mapped_column(Float, nullable=False)

    predicted_financial_exposure: Mapped[float | None] = mapped_column(Numeric(18, 2), nullable=True)
    financial_lower_bound: Mapped[float | None] = mapped_column(Numeric(18, 2), nullable=True)
    financial_upper_bound: Mapped[float | None] = mapped_column(Numeric(18, 2), nullable=True)

    model_name: Mapped[str] = mapped_column(String(100), index=True, nullable=False)
    model_version: Mapped[str] = mapped_column(String(50), index=True, nullable=False)
    feature_version: Mapped[str] = mapped_column(String(100), nullable=False)
    dataset_version: Mapped[str] = mapped_column(String(100), nullable=False)

    prediction_timestamp: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), index=True, default=get_utc_now, nullable=False
    )

    # For Backtesting / Performance tracking later
    actual_risk: Mapped[float | None] = mapped_column(Float, nullable=True)
    prediction_error: Mapped[float | None] = mapped_column(Float, nullable=True)
    
    prediction_metadata: Mapped[dict[str, Any] | None] = mapped_column("metadata", JSONB, nullable=True)
    
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=get_utc_now, nullable=False)

    # Relationships
    organization: Mapped["Organization"] = relationship("Organization", backref="risk_predictions")
    asset: Mapped["Asset"] = relationship("Asset", backref="risk_predictions")
    risk_score: Mapped["RiskScore"] = relationship("RiskScore", backref="risk_predictions")
